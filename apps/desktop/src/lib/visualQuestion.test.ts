import { describe, expect, it } from 'vitest';
import { requiresScreenContext } from './visualQuestion';

describe('requiresScreenContext', () => {
  it.each([
    'Что выведет этот код?',
    'Посмотри на экран и скажи, где ошибка',
    'Объясни этот фрагмент',
    'Что произойдёт в данном выражении?',
    'Скажи мне решение этого задания и в каком порядке вызываются фикстуры',
    'Перед тобой сейчас задание.',
    'Перед тобой сейчас задание. Реши его.',
    'А ты можаш мне імна сказаць сам рашэнне гэтага задачы?',
    'Решиво.',
    'Очередность выполнения задачи проанализировать код и написать в тесте корректный ассерт для ордера.',
    'Условия описания задачи, порядок выполнения фикстур, что проверяем.',
    'На экране виден код с фикстурами. Какой будет порядок?',
    'Перед тобой задача с кодом. Какой ассерт будет корректным?',
    'В редакторе виден текущий пример. Какой получится результат?',
    'В каком порядке выполняются фикстуры в этом коде?',
    'На экране код: «в каком порядке выполняются pytest-фикстуры?»',
    'What will this code print?',
    'Explain the snippet on the screen',
  ])('routes deictic task to vision: %s', (question) => {
    expect(requiresScreenContext(question)).toBe(true);
  });

  it.each([
    'Что такое генератор?',
    'Напиши функцию с аргументом по умолчанию',
    'Как работает git rebase?',
    'В каком порядке фикстуры должны выполняться?',
    'В каком порядке текстуры должны наследоваться?',
    'Расскажите, в каком порядке фикстуры должны выполняться?',
    'Объясните, в каком порядке выполняются pytest-фикстуры?',
    'Расскажите (в каком порядке фикстуры должны выполняться)?',
    'Объясните: «в каком порядке выполняются pytest-фикстуры?»',
    'What is a context manager?',
  ])('keeps self-contained question on text route: %s', (question) => {
    expect(requiresScreenContext(question)).toBe(false);
  });
});
